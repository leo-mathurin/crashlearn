"""Export deterministic policies and build self-contained tournament agents (E-25)."""

import ast
from pathlib import Path

import onnx
import torch

from crashlearn import features, history


class DeterministicPPO(torch.nn.Module):
    def __init__(self, policy):
        super().__init__()
        self.policy = policy
        self.register_buffer("action_low", torch.as_tensor(policy.action_space.low.copy()))
        self.register_buffer("action_high", torch.as_tensor(policy.action_space.high.copy()))

    def forward(self, observations):
        actions = self.policy._predict(observations, deterministic=True)
        return torch.maximum(torch.minimum(actions, self.action_high), self.action_low)


def export_onnx(policy: torch.nn.Module, path: Path, sample_input: torch.Tensor) -> None:
    """A float32 feature batch -> actions, opset 17, weights in model.onnx.data."""
    path = Path(path)
    data_path = path.with_name(path.name + ".data")
    if path.exists() or data_path.exists():
        raise FileExistsError(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    policy = policy.cpu().eval()
    torch.onnx.export(
        policy,
        sample_input.cpu(),
        str(path),
        opset_version=17,
        dynamo=False,
        input_names=["features"],
        output_names=["actions"],
        dynamic_axes={"features": {0: "batch"}, "actions": {0: "batch"}},
    )
    model = onnx.load(path)
    onnx.save_model(
        model,
        path,
        save_as_external_data=True,
        all_tensors_to_one_file=True,
        location=data_path.name,
        size_threshold=0,
    )
    onnx.checker.check_model(str(path))


def _body(module) -> str:
    source = Path(module.__file__).read_text()
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    removed = set()
    for node in tree.body:
        if isinstance(node, ast.Import | ast.ImportFrom) or (
            node is tree.body[0]
            and isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            removed.update(range(node.lineno - 1, node.end_lineno))
    return "".join(line for i, line in enumerate(lines) if i not in removed)


